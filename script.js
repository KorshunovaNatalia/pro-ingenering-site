/* Переключение страниц */
function showPage(pageId) {
    const pages = document.querySelectorAll('.page');
    pages.forEach(page => page.classList.remove('active'));
    const target = document.getElementById(pageId);
    if (target) target.classList.add('active');

    updateMetaTags(pageId);

    const links = document.querySelectorAll('.nav__link');
    links.forEach(link => link.classList.remove('active'));
    links.forEach(link => {
        if (link.getAttribute('onclick') === `showPage('${pageId}')`) link.classList.add('active');
    });

    const nav = document.querySelector('.nav');
    nav.classList.remove('open');

    if (pageId === 'services') {
        if (localStorage.getItem('fromMain')) {
            navigationSource = 'main';
            localStorage.removeItem('fromMain');
        } else {
            navigationSource = 'menu';
        }
        setServicesBreadcrumbs();
    }

    if (pageId === 'home') {
        navigationSource = 'menu';
        localStorage.removeItem('fromMain');
    }

    if (pageId !== 'contacts') {
        mapInitialized = false;
        myMapInstance = null;
        const mapContainer = document.getElementById('map');
        if (mapContainer) {
            mapContainer.innerHTML = '';
        }
    }

    if (pageId === 'contacts') {
        setTimeout(() => {
            initMap();
        }, 300);
    }

    window.scrollTo({ top: 0, behavior: 'smooth' });
}

