/* Обновление видимости кнопок слайдера */
function updateLicenseButtons() {
    const slides = document.querySelectorAll('#licenseTrack .license-slider__slide');
    const leftBtn = document.getElementById('licenseLeftBtn');
    const rightBtn = document.getElementById('licenseRightBtn');

    if (!slides.length || !leftBtn || !rightBtn) return;

    let visibleItems = 4;
    if (window.innerWidth <= 1024) visibleItems = 2;
    if (window.innerWidth <= 768) visibleItems = 1;

    const maxSlide = Math.max(0, slides.length - visibleItems);

    if (licenseCurrentSlide <= 0) {
        leftBtn.style.display = 'none';
    } else {
        leftBtn.style.display = 'flex';
    }

    if (licenseCurrentSlide >= maxSlide) {
        rightBtn.style.display = 'none';
    } else {
        rightBtn.style.display = 'flex';
    }
}

/* Переключение слайдера */
function licenseSlide(direction) {
    const track = document.getElementById('licenseTrack');
    const slides = document.querySelectorAll('#licenseTrack .license-slider__slide');

    if (!track || !slides.length) return;

    let visibleItems = 4;
    if (window.innerWidth <= 1024) visibleItems = 2;
    if (window.innerWidth <= 768) visibleItems = 1;

    const maxSlide = Math.max(0, slides.length - visibleItems);

    licenseCurrentSlide = Math.max(0, Math.min(licenseCurrentSlide + direction, maxSlide));

    const slideWidth = slides[0].offsetWidth + 20;
    track.style.transform = `translateX(-${licenseCurrentSlide * slideWidth}px)`;

    updateLicenseButtons();
}


