/* Инициализация карты */
function initMap() {
    const mapContainer = document.getElementById('map');
    if (!mapContainer) return;

    if (mapInitialized || mapContainer.innerHTML.trim() !== '') {
        if (myMapInstance) {
            setTimeout(() => {
                try {
                    myMapInstance.container.fitToViewport();
                } catch (e) {
                    console.warn('Не удалось обновить карту');
                }
            }, 100);
        }
        return;
    }

    if (typeof ymaps === 'undefined') {
        console.warn('Yandex Maps API не загружен. Показываем заглушку.');
        mapContainer.innerHTML = `
            <div style="display:flex;align-items:center;justify-content:center;height:100%;background:#e8e8e8;color:#555;font-size:18px;border-radius:var(--radius-lg);padding:20px;text-align:center;">
                <div>
                    <p>Карта временно недоступна</p>
                    <p style="font-size:14px;color:#999;">г. Тверь, ул. Красные Горки, д. 39</p>
                </div>
            </div>
        `;
        mapInitialized = true;
        return;
    }

    try {
        ymaps.ready(function() {
            if (mapInitialized || mapContainer.innerHTML.trim() !== '') {
                return;
            }

            myMapInstance = new ymaps.Map('map', {
                center: [56.854173, 35.959246],
                zoom: 13,
                controls: ['zoomControl']
            });

            var myPlacemark = new ymaps.Placemark([56.854173, 35.959246], {
                hintContent: 'ООО «Про-Инженеринг»',
                balloonContent: '170100, г. Тверь, ул. Красные Горки, д. 39, помещ. 6П.'
            });

            myMapInstance.geoObjects.add(myPlacemark);
            mapInitialized = true;

            setTimeout(() => {
                try {
                    myMapInstance.container.fitToViewport();
                } catch (e) {
                    console.warn('Не удалось подогнать карту под размер');
                }
            }, 200);
        });
    } catch (e) {
        console.error('Ошибка при инициализации карты:', e);
        mapContainer.innerHTML = `
            <div style="display:flex;align-items:center;justify-content:center;height:100%;background:#e8e8e8;color:#555;font-size:18px;border-radius:var(--radius-lg);padding:20px;text-align:center;">
                <div>
                    <p>Карта временно недоступна</p>
                    <p style="font-size:14px;color:#999;">г. Тверь, ул. Красные Горки, д. 39</p>
                </div>
            </div>
        `;
        mapInitialized = true;
    }
}

/* Обновление карты при изменении размера окна */
function refreshMap() {
    if (myMapInstance) {
        try {
            const mapContainer = document.getElementById('map');
            if (mapContainer && mapContainer.offsetParent !== null) {
                myMapInstance.container.fitToViewport();
            }
        } catch (e) {
            console.error('Ошибка при обновлении карты:', e);
        }
    }
}


