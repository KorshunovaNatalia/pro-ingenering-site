/* Показ сообщения об ошибке */
function showError(input, message) {
    const parent = input.closest('.form__group');
    if (!parent) return;
    const errorEl = parent.querySelector('.form__error');
    if (errorEl) {
        errorEl.textContent = message;
        errorEl.style.display = 'block';
    }
}

/* Скрытие сообщения об ошибке */
function hideError(input) {
    const parent = input.closest('.form__group');
    if (!parent) return;
    const errorEl = parent.querySelector('.form__error');
    if (errorEl) {
        errorEl.style.display = 'none';
    }
}

/* Валидация ИНН (только цифры, 10 или 12 символов) */
function validateInn(input) {
    input.value = input.value.replace(/[^0-9]/g, '');
    if (input.value.length > 12) input.value = input.value.slice(0, 12);

    const isValid = input.value.length === 0 || input.value.length === 10 || input.value.length === 12;
    if (input.value.length > 0 && !isValid) {
        input.classList.add('error');
        showError(input, 'Введите 10 или 12 цифр');
    } else {
        input.classList.remove('error');
        hideError(input);
    }
    return isValid || input.value.length === 0;
}

/* Валидация ФИО (буквы, пробелы, дефисы, минимум 2 слова) */
function validateName(input) {
    input.value = input.value.replace(/[^a-zA-Zа-яА-ЯёЁ\s\-]/g, '');

    const trimmed = input.value.trim();
    const words = trimmed.split(/\s+/).filter(w => w.length > 0);

    const hasValidWords = words.length >= 2 && words.every(w => w.length >= 2);
    const hasNoRepeating = !/(.)\1{3,}/i.test(trimmed);

    const isValid = trimmed.length > 0 && hasValidWords && hasNoRepeating;

    if (trimmed.length === 0) {
        input.classList.add('error');
        showError(input, 'Заполните поле');
    } else if (!hasValidWords) {
        input.classList.add('error');
        showError(input, 'Введите фамилию и имя');
    } else if (!hasNoRepeating) {
        input.classList.add('error');
        showError(input, 'Некорректный ввод');
    } else {
        input.classList.remove('error');
        hideError(input);
    }

    return isValid;
}

/* Валидация должности (минимум 3 символа, без повторений) */
function validatePosition(input) {
    const trimmed = input.value.trim();

    const hasNoRepeating = !/(.)\1{3,}/i.test(trimmed);
    const hasMinLength = trimmed.length >= 3;

    const isValid = trimmed.length > 0 && hasMinLength && hasNoRepeating;

    if (trimmed.length === 0) {
        input.classList.add('error');
        showError(input, 'Заполните поле');
    } else if (!hasMinLength) {
        input.classList.add('error');
        showError(input, 'Минимум 3 символа');
    } else if (!hasNoRepeating) {
        input.classList.add('error');
        showError(input, 'Некорректный ввод');
    } else {
        input.classList.remove('error');
        hideError(input);
    }

    return isValid;
}

/* Общая валидация формы */
function validateForm(formId) {
    const form = document.getElementById(formId);
    if (!form) return false;

    let isValid = true;

    const inputs = form.querySelectorAll('input[type="text"], input:not([type="checkbox"]):not([type="submit"])');

    inputs.forEach(input => {
        const name = input.getAttribute('name') || input.id;

        if (name && (name.includes('inn') || input.id === 'inn')) {
            validateInn(input);
        } else if (name && (name.includes('fio') || input.id === 'fio')) {
            if (!validateName(input)) {
                isValid = false;
            }
        } else if (name && (name.includes('position') || input.id === 'position')) {
            if (!validatePosition(input)) {
                isValid = false;
            }
        } else {
            if (input.hasAttribute('required') && input.value.trim() === '') {
                input.classList.add('error');
                showError(input, 'Заполните поле');
                isValid = false;
            } else {
                input.classList.remove('error');
                hideError(input);
            }
        }
    });

    return isValid;
}

/* Настройка "живой" валидации при вводе */
function setupLiveValidation() {
    const fioContact = document.getElementById('fio');
    const posContact = document.getElementById('position');
    const innContact = document.getElementById('inn');

    if (fioContact) {
        fioContact.addEventListener('input', function() { validateName(this); });
        fioContact.addEventListener('blur', function() { validateName(this); });
    }

    if (posContact) {
        posContact.addEventListener('input', function() { validatePosition(this); });
        posContact.addEventListener('blur', function() { validatePosition(this); });
    }

    if (innContact) {
        innContact.addEventListener('input', function() { validateInn(this); });
        innContact.addEventListener('blur', function() { validateInn(this); });
    }

    const modalForms = document.querySelectorAll('#applicationForm input[type="text"]');
    modalForms.forEach(input => {
        const name = input.getAttribute('name') || '';
        if (name.includes('fio')) {
            input.addEventListener('input', function() { validateName(this); });
            input.addEventListener('blur', function() { validateName(this); });
        } else if (name.includes('position')) {
            input.addEventListener('input', function() { validatePosition(this); });
            input.addEventListener('blur', function() { validatePosition(this); });
        } else if (name.includes('inn')) {
            input.addEventListener('input', function() { validateInn(this); });
            input.addEventListener('blur', function() { validateInn(this); });
        }
    });
}


